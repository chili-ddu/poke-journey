"""Build gym evolution families from Platinum data and authored Kanto parties.

Level evolutions use native thresholds. Authored item/trade evolutions use
their declared growth-party readiness level, preserving earlier thresholds
for existing forms. This is never a natural evolution-level claim.
"""
import json
from pathlib import Path
from gym_rosters import load as load_rosters

ROOT = Path(__file__).resolve().parents[1]


def build():
    species = json.loads((ROOT / "assets/data/species.json").read_text())
    origins = json.loads((ROOT / "assets/data/gym_leaders.json").read_text())["origins"]
    parties = {key: value["party"] for key, value in origins.items()}
    parties["leader_brock"] = [["geodude", 12], ["kabuto", 13], ["onix", 14], ["aerodactyl", 16]]
    parties["leader_misty"] = [["staryu", 18], ["starmie", 21]]
    rosters=load_rosters()
    for id,cfg in rosters['leaders'].items():parties[id]=cfg['growth_party']
    allowed={sid for sid,sp in species.items() if sp['dex']<=151} | set(rosters['baby_roots'])
    edges = {}
    previous = {}
    for sid, sp in species.items():
        if sid not in allowed:
            continue
        data = json.loads((ROOT / f"third_party/pokeplatinum/res/pokemon/{sid}/data.json").read_text())
        for evolution in data.get("evolutions", []):
            target = evolution[-1].removeprefix("SPECIES_").lower()
            if target not in allowed:
                continue
            edge = {"from": sid, "to": target, "method": evolution[0]}
            if evolution[0] == "EVO_LEVEL":
                edge["level"] = evolution[1]
            edges.setdefault(sid, []).append(edge)
            previous[target] = edge
    leaders = {}
    for id, party in parties.items():
        families = {}
        slots = []
        for sid, level, *_ in party:
            path = []
            root = sid
            while root in previous:
                edge = previous[root]
                path.insert(0, edge)
                root = edge["from"]
            family = families.setdefault(root, {root: {"species": root, "level": 1, "method": "base"}})
            minimum = 1
            for edge in path:
                minimum = max(minimum, edge.get("level", level))
                entry = {"species": edge["to"], "level": minimum, "method": edge["method"]}
                old = family.get(edge["to"])
                if old is None or minimum < old["level"]:
                    family[edge["to"]] = entry
            slots.append(root)
        for root, family in families.items():
            queue = list(family)
            for sid in queue:
                for edge in edges.get(sid, []):
                    if edge["method"] != "EVO_LEVEL" or edge["to"] in family:
                        continue
                    family[edge["to"]] = {"species": edge["to"], "level": max(family[sid]["level"], edge["level"]), "method": edge["method"]}
                    queue.append(edge["to"])
        leaders[id] = {"slots": slots, "families": {root: sorted(family.values(), key=lambda row: row["level"]) for root, family in families.items()}}
    return leaders


def main():
    leaders = build()
    data = {"level_bonus": [3, 7], "maximum_level": 100, "leaders": leaders,
            "special_evolution_policy": "Authored item/trade forms use their declared growth-party readiness level, preserving existing-form thresholds; native level evolutions keep Platinum thresholds. No unauthored item/trade branches are added."}
    (ROOT / "assets/data/gym_growth.json").write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n")
    output = "extends RefCounted\n# Generated by tools/gym_growth.py from native evolution data and authored parties.\n"
    output += "const LEVEL_BONUS := Vector2i(3, 7)\nconst MAX_LEVEL := 100\n"
    output += "const LEADERS := " + json.dumps(leaders, ensure_ascii=False, indent=2) + "\n"
    (ROOT / "scripts/data/gym_growth_data.gd").write_text(output)
    names = sorted({stage["species"] for cfg in leaders.values() for family in cfg["families"].values() for stage in family})
    missing = [sid for sid in names if not (ROOT / f'assets/sprites/{json.loads((ROOT / "assets/data/species.json").read_text())[sid]["dex"]:04d}/Walk-Anim.png').exists()]
    print("Gym growth:", len(leaders), "leaders,", len(names), "forms; missing native sprite forms:", missing)


if __name__ == "__main__":
    main()
