"""Export authored gym parties independently of the preserved FRLG originals."""
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]


def load():
    return json.loads((ROOT/'assets/data/gym_rosters.json').read_text())


def main():
    data=load()
    species=json.loads((ROOT/'assets/data/species.json').read_text())
    moves=json.loads((ROOT/'assets/data/moves.json').read_text())
    parties={}
    for leader,entry in data['leaders'].items():
        count=5 if leader=='leader_giovanni' else 4
        assert len(entry['party'])==len(entry['growth_party'])==count
        assert len({row[0] for row in entry['party']})==count
        for row in entry['party']:
            assert row[0] in species
            for move in row[2]:assert move in moves,(leader,move)
        parties[leader]={'party':entry['party'],'ivs':[0]*count}
    output='extends RefCounted\n# Generated by tools/gym_rosters.py; native source parties remain archived.\n'
    output+='const PARTIES := '+json.dumps(parties,ensure_ascii=False,indent=2)+'\n'
    (ROOT/'scripts/data/gym_rosters.gd').write_text(output)
    print('Authored gym rosters:',{leader:len(entry['party']) for leader,entry in parties.items()})


if __name__=='__main__':main()
