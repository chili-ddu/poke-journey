"""Generate native water terrain independently of baked/customized map artwork."""
import json,struct
import frlg_map as fm
ROOT=fm.ROOT
SCOPE=['PalletTown','ViridianCity','Route4','CeruleanCity','Route6','VermilionCity']
# Directional currents are water too. Waterfalls retain their separate
# blocked traversal tiles until a waterfall movement rule is implemented.
SURFABLE={0x10,0x11,0x12,0x15,0x1a,0x1b,0x50,0x51,0x52,0x53}
def rows(folder):
 lay=fm.layout_of(fm.map_json(folder)['layout']); attrs={}
 for base,d in [(0,fm.tileset_dir(lay['primary_tileset'])),(640,fm.tileset_dir(lay['secondary_tileset']))]:
  raw=fm.fetch(d+'/metatile_attributes.bin').read_bytes()
  attrs.update({base+i:struct.unpack_from('<I',raw,i*4)[0]&511 for i in range(len(raw)//4)})
 w,h=lay['width'],lay['height']
 blocks=struct.unpack(f'<{w*h}H',fm.fetch(lay['blockdata_filepath']).read_bytes())
 # Seafoam uses scripted currents instead of the native collision bits to
 # reject an unsolved crossing. Its water surface stays at floor height.
 def water(block):
  behavior=attrs.get(block&1023)
  return behavior in SURFABLE and (((block>>10)&3)==0 or (folder.startswith('SeafoamIslands') and behavior in {0x50,0x51,0x52,0x53}))
 return [''.join('1' if water(blocks[y*w+x]) else '0' for x in range(w)) for y in range(h)]
def main():
 group=json.loads((fm.TP/'src/data/wild_encounters.json').read_text())['wild_encounter_groups'][0]
 fields={f['type']:f for f in group['fields']};tables={}
 for folder in SCOPE:
  native=next(e for e in group['encounters'] if e['map']=='MAP_'+fm.snake(folder).upper() and e['base_label'].endswith('FireRed'))
  cfg={}
  for field,key in [('water_mons','water_encounters'),('fishing_mons','fishing')]:
   data=native[field]; weights=fields[field]['encounter_rates']
   slots=[[m['species'].removeprefix('SPECIES_').lower(),m['min_level'],w,m['max_level']] for m,w in zip(data['mons'],weights,strict=True)]
   cfg[key]={rod:[slots[i] for i in indices] for rod,indices in fields[field]['groups'].items()} if field=='fishing_mons' else slots
   cfg['water_encounter_rate' if field=='water_mons' else 'fishing_encounter_rate']=data['encounter_rate']
  tables[fm.snake(folder)]=cfg
 (ROOT/'scripts/data/kanto_water_data.gd').write_text('# Generated by tools/kanto_water.py from FireRed native encounters.\nclass_name KantoWaterData\nextends RefCounted\nconst TABLES := '+json.dumps(tables,ensure_ascii=False,indent=2)+'\n')
 for region in ['kanto_south','kanto_north','kanto_east']:
  j=json.loads((ROOT/'assets/maps'/region/'map.json').read_text()); mask=[['0']*j['width'] for _ in range(j['height'])]
  for area in j['areas']:
   folder=next((f for f in SCOPE if fm.snake(f)==area['id']),None)
   if not folder:continue
   native_rows=rows(folder)
   assert len(native_rows)==area['h'] and len(native_rows[0])==area['w']
   for y,row in enumerate(native_rows):
    for x,cell in enumerate(row):
     if 0<area['y']+y<j['height']-1 and 0<area['x']+x<j['width']-1:mask[area['y']+y][area['x']+x]=cell
  (ROOT/'assets/maps'/region/'water.json').write_text(json.dumps({'water':[''.join(row) for row in mask]},separators=(',',':'))+'\n')
  print(region,sum(row.count('1') for row in mask),'water tiles')
if __name__=='__main__':main()
