from pathlib import Path
from road_trainers import native_data,party_members

ROOT=Path(__file__).resolve().parents[1]
STAGES=[
    {"id":"route22_early","area":"route22","map":"","rect":[33,4,1,3],"from":[25,4],"native":"ROUTE22_EARLY","arena":"arena_route1","name":"22번도로 첫 재전","rule":"before_brock"},
    {"id":"lavender","area":"lavender_town","map":"","rect":[17,7,3,2],"from":[15,8],"native":"POKEMON_TOWER","arena":"arena_route1","name":"보라시티 타워 앞","rule":"always"},
    {"id":"silph","area":"silph_co_7f","map":"silph_co_7f","rect":[2,4,1,2],"from":[2,6],"native":"SILPH","arena":"arena_silph_rival","name":"실프주식회사 7층","rule":"always"},
    {"id":"route22_late","area":"route22","map":"","rect":[33,4,1,3],"from":[25,4],"native":"ROUTE22_LATE","arena":"arena_route1","name":"22번도로 마지막 재전","rule":"all_leaders"}]
INTRO={
    "route22_early":["또 만났네! 벌써 여기까지 왔어?\n나도 친구들과 훈련 중이었다고!","지난번처럼 쉽게 놓치지 않아.\n이번엔 꼭 너를 잡겠어!"],
    "lavender":["그 탑에 들어가려는 거야?\n혼자서도 겁이 없네!","우리도 더 강해졌다고.\n탑에 들어가기 전에 승부다!"],
    "silph":["이 건물까지 혼자 들어왔어?\n어디에 가도 네 소식이 들리네!","이제는 내 동료들도 많이 자랐어.\n이번엔 우리 실력을 보여 주겠어!"],
    "route22_late":["여덟 관장을 전부 이겼다며?\n나도 계속 기다리고 있었다고!","우리도 이제 완전히 달라졌어.\n최고를 향해 가기 전에 승부다!"]}


def build():
    native,parties=native_data();trainers={};origins={}
    for stage in STAGES:
        for form in ["squirtle","bulbasaur","charmander"]:
            constant="TRAINER_RIVAL_"+stage["native"]+"_"+form.upper()
            raw=native[constant]
            pointer=re.search(r"\.party\s*=\s*\w+\((sParty_\w+)\)",raw)[1]
            party,ivs=party_members(parties[pointer])
            id="rival_"+stage["id"]+"_"+form
            trainers[id]={"class":"rival","name":"GREEN","name_ko":"그린","sprite":"blue","arena":stage["arena"],
                "party":party,"ivs":[v*31//255 for v in ivs],
                "intro":{"ko":INTRO[stage["id"]],"en":["There you are again!\nMy friends and I have trained hard.","This time, we're going to catch you!\nLet's see how strong you've become!"]},
                "defeat":{"ko":["또 졌다고?\n역시 넌 보통 포켓몬이 아니구나!","이거나 받아 둬.\n다음엔 꼭 내가 이길 테니까!"],"en":["I lost again?\nYou're no ordinary POKéMON!","Take these for your journey.\nI'll win next time!"]},
                "farewell":{"ko":["더 강해져서 다시 만나자!"],"en":["Smell you later!"]},
                "after":{"ko":["다음에 만날 때까지\n더 강해지고 있으라고!"],"en":["Keep getting stronger\nuntil we meet again!"]}}
            origins[id]={"trainer":constant,"party_id":pointer,"party":party,"native_ivs":ivs,"stage":stage["id"]}
    return trainers,origins


def main():
    trainers,origins=build()
    text="extends RefCounted\n# Generated by tools/rival_progression.py; existing rival battles are preserved.\n"
    text+="const STAGES := "+json.dumps(STAGES,ensure_ascii=False,indent=2)+"\n"
    text+="const TRAINERS := "+json.dumps(trainers,ensure_ascii=False,indent=2)+"\n"
    text+='const THEMES := {"arena_silph_rival":{"map":"res://assets/maps/arena_silph_rival","tiles":{}}}\n'
    text+='const PLACES := {"arena_silph_rival":{"name":"SILPH CO.","name_ko":"실프주식회사","theme":"arena_silph_rival","arena_field":true,"battle_style":"room","count":0,"encounters":[]}}\n'
    (ROOT/"scripts/data/rival_progression.gd").write_text(text)
    (ROOT/"assets/data/rival_progression.json").write_text(json.dumps({"stages":STAGES,"origins":origins},ensure_ascii=False,indent=2)+"\n")
    print("New rival stages:",[(s["id"],len(trainers["rival_"+s["id"]+"_squirtle"]["party"])) for s in STAGES])


if __name__=="__main__":main()
