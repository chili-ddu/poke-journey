"""Native Route 9/10, Rock Tunnel and the Pikachu rescue field. Existing saves keep their coordinates."""
import json
import shutil
from pathlib import Path
import frlg_map as fm
import kanto_wild

ROOT=fm.ROOT
OUT=ROOT/'assets/maps'
REGION='kanto_rock_pass'
FOLDERS=['Route9','Route10','LavenderTown']
CAVES=['RockTunnel_1F','RockTunnel_B1F']

def load(name):return json.loads((OUT/name/'map.json').read_text())
def save(name,j):(OUT/name/'map.json').write_text(json.dumps(j,ensure_ascii=False,indent=0)+'\n')

def definitions():
    titles={'route9':'9번도로','route10':'10번도로','lavender_town':'보라타운'}
    areas={fm.snake(f):json.loads(kanto_wild.area(f,titles[fm.snake(f)])) for f in FOLDERS}
    themes={REGION:dict(map='res://assets/maps/'+REGION,tiles={})}
    warps={fm.snake(f):REGION for f in FOLDERS}
    places={REGION:dict(name='ROCK PASS',name_ko='돌산터널 주변',theme=REGION,overworld=True,count=0,encounters=[],areas=areas)}
    music={fm.snake(f):fm.map_json(f)['music'].lower() for f in FOLDERS}
    for f in CAVES:
        name=fm.snake(f);title='돌산터널 '+('지하 1층' if 'B1F' in f else '1층')
        cfg=json.loads(kanto_wild.area(f,title));cfg['encounter_terrain']='cave'
        themes[name]=dict(map='res://assets/maps/'+name,tiles={});warps[name]=name
        places[name]=dict(name=f.upper(),name_ko=title,theme=name,overworld=True,battle_style='room',count=0,encounters=[],areas={name:cfg})
        music[name]=fm.map_json(f)['music'].lower()
    name='arena_pikachu_rescue'
    themes[name]=dict(map='res://assets/maps/'+name,tiles={})
    places[name]=dict(name='PIKACHU RESCUE',name_ko='피카츄 구출',theme=name,arena_field=True,count=0,encounters=[])
    text='# Generated by tools/rock_pass.py.\nextends RefCounted\n'
    for key,value in [('THEMES',themes),('WARP_MAPS',warps),('DUNGEONS',places),('MUSIC',music)]:
        text+='const '+key+' := '+json.dumps(value,ensure_ascii=False,indent=2)+'\n'
    (ROOT/'scripts/data/rock_pass.gd').write_text(text)

def connect_city():
    native=fm.bake_layout(fm.layout_of(fm.map_json('CeruleanCity')['layout']))
    road=fm.bake_layout(fm.layout_of(fm.map_json('Route9')['layout']))
    lanes=[y for y in range(1,19) if all(native['solid'][y+10][native['w']-1-i]==0 and road['solid'][y][i]==0 for i in (0,1))]
    assert lanes
    j=load(REGION);rows=[list(r) for r in j['solid']]
    for row in rows:row[0]='1'
    j['warps']=[w for w in j['warps'] if not w.get('rock_pass_link')]
    for y in lanes:
        rows[y][0]='0'
        j['warps'].append(dict(x=0,y=y,map='route9',index=3000+y,to='cerulean_city',to_warp=3000+y,arrival_dir=[1,0],edge_transition=True,rock_pass_link=True))
    j['solid']=[''.join(r) for r in rows];j['start']=[2*16+8,lanes[0]*16+8];save(REGION,j)
    from north_terrain import remove_cells
    path=OUT/REGION/'hd2d_cards.json';cards=json.loads(path.read_text())
    cards['cards']=remove_cells(cards['cards'],{(0,y) for y in lanes})
    path.write_text(json.dumps(cards,ensure_ascii=False,indent=2)+'\n')
    for name in ['kanto_field','kanto_north']:
        m=load(name);city=next(a for a in m['areas'] if a['id']=='cerulean_city')
        previous={(w['x'],w['y']) for w in m['warps'] if w.get('rock_pass_link')}
        m['warps']=[w for w in m['warps'] if not w.get('rock_pass_link')]
        cells={(city['x']+city['w']-1,city['y']+10+y) for y in lanes}
        rows=[list(r) for r in m['solid']]
        for y in lanes:
            x=city['x']+city['w']-1;yy=city['y']+10+y;rows[yy][x]='0'
            m['warps'].append(dict(x=x,y=yy,map='cerulean_city',index=3000+y,to='route9',to_warp=3000+y,arrival_dir=[-1,0],edge_transition=True,rock_pass_link=True))
        m['solid']=[''.join(r) for r in rows];save(name,m)
        patch_path=OUT/name/'collision_patch.json'
        patch=json.loads(patch_path.read_text()) if patch_path.exists() else dict(open=[],block=[])
        patch['block']=[c for c in patch.get('block',[]) if tuple(c) not in cells]
        patch['open']=[c for c in patch.get('open',[]) if tuple(c) not in cells|previous]+[list(c) for c in sorted(cells)]
        patch_path.write_text(json.dumps(patch,indent=2)+'\n')
        path=OUT/name/'hd2d_cards.json';cards=json.loads(path.read_text());cards['cards']=remove_cells(cards['cards'],cells);path.write_text(json.dumps(cards,ensure_ascii=False,indent=2)+'\n')
    print('Cerulean east lanes',lanes)

def main():
    definitions()
    fm.bake(FOLDERS,REGION,(2,9),True)
    for f in CAVES:fm.bake([f],fm.snake(f),(38,29) if 'B1F' in f else (17,3),False)
    from kanto_water import rows as water_rows
    j=load(REGION);mask=[list('0'*j['width']) for _ in range(j['height'])]
    for a,f in zip(j['areas'],FOLDERS):
        for y,row in enumerate(water_rows(f)):mask[y+a['y']][a['x']:a['x']+a['w']]=row
    (OUT/REGION/'water.json').write_text(json.dumps(dict(water=[''.join(r) for r in mask]))+'\n')
    # The existing natural court already has a clear apron and upright perimeter.
    source=OUT/'arena_route1';dest=OUT/'arena_pikachu_rescue';dest.mkdir(exist_ok=True)
    for name in ['bottom.png','top.png','preview.png','map.json']:
        shutil.copyfile(source/name,dest/name)
    j=load('arena_pikachu_rescue');j['areas'][0]['id']='arena_pikachu_rescue';save('arena_pikachu_rescue',j)
    import hd2d_cards
    for name in [REGION,'rock_tunnel_1f','rock_tunnel_b1f','arena_pikachu_rescue']:hd2d_cards.build(name)
    connect_city()
    print('Route 10 rescue: native walkable corner behind the northern fence (17,4).')

if __name__=='__main__':main()
