"""Native Route 11 and Diglett's Cave shortcut, without moving existing saves."""
import json
import frlg_map as fm
import kanto_wild
from north_terrain import remove_cells

OUT=fm.ROOT/'assets/maps'
FOLDERS=['Route11','DiglettsCave_NorthEntrance','DiglettsCave_SouthEntrance','DiglettsCave_B1F',
         'Route11_EastEntrance_1F','Route11_EastEntrance_2F','Route2_House','Route2_EastBuilding']
CAVES={fm.snake(f) for f in FOLDERS if f.startswith('DiglettsCave')}
NAMES={'route11':'11번도로','digletts_cave_north_entrance':'디그다굴 북쪽 입구',
       'digletts_cave_south_entrance':'디그다굴 남쪽 입구','digletts_cave_b1f':'디그다굴',
       'route11_east_entrance_1f':'11번도로 동쪽 관문','route11_east_entrance_2f':'11번도로 관문 2층',
       'route2_house':'2번도로 민가','route2_east_building':'2번도로 동쪽 관문'}

def read(name,file='map.json'):return json.loads((OUT/name/file).read_text())
def write(name,value,file='map.json'):(OUT/name/file).write_text(json.dumps(value,ensure_ascii=False,indent=2)+'\n')

def coast_encounters():
    group=json.loads(kanto_wild.SOURCE.read_text())['wild_encounter_groups'][0]
    fields={field['type']:field for field in group['fields']}
    native=next(e for e in group['encounters'] if e['map']=='MAP_ROUTE11' and e['base_label'].endswith('FireRed'))
    cfg={}
    for field,key in [('water_mons','water_encounters'),('fishing_mons','fishing')]:
        data=native[field]
        slots=[[m['species'].removeprefix('SPECIES_').lower(),m['min_level'],weight,m['max_level']]
               for m,weight in zip(data['mons'],fields[field]['encounter_rates'],strict=True)]
        cfg[key]={rod:[slots[i] for i in indices] for rod,indices in fields[field]['groups'].items()} if field=='fishing_mons' else slots
        cfg['water_encounter_rate' if field=='water_mons' else 'fishing_encounter_rate']=data['encounter_rate']
    return cfg

def gate_stairs(d,j,metadata):
    from PIL import Image
    name=d.name
    cells={(x,y) for x in range(8,10) for y in range(8,11)} if name.endswith('2f') else {(10,y) for y in range(9,12)}
    metadata['cards']=remove_cells(metadata['cards'],cells)
    floor=Image.open(d/'hd2d_floor.png').convert('RGBA')
    bottom=Image.open(d/'bottom.png').convert('RGBA');top=Image.open(d/'top.png').convert('RGBA');pad=j['pad']
    for x,y in cells:
        box=((x+pad)*16,(y+pad)*16,(x+pad+1)*16,(y+pad+1)*16)
        tile=bottom.crop(box);tile.alpha_composite(top.crop((x*16,y*16,(x+1)*16,(y+1)*16)))
        floor.paste(tile,box[:2])
    floor.save(d/'hd2d_floor.png')
    metadata['flat_stair_tiles']=[list(c) for c in sorted(cells)]
    return metadata

def definitions():
    themes={};warps={};places={};music={}
    for folder in FOLDERS:
        name=fm.snake(folder)
        themes[name]=dict(map='res://assets/maps/'+name,tiles={});warps[name]=name
        cfg=dict(name=folder.upper(),name_ko=NAMES[name],theme=name,count=0,encounters=[])
        cfg['overworld' if name=='route11' or name in CAVES else 'indoor']=True
        if name=='route11' or name in CAVES:
            area=json.loads(kanto_wild.area(folder,NAMES[name]))
            if name=='route11':area.update(coast_encounters())
            if name in CAVES:area['encounter_terrain']='cave';cfg['battle_style']='room'
            cfg['areas']={name:area}
        places[name]=cfg;music[name]=fm.map_json(folder)['music'].lower()
    text='# Generated by tools/route11_diglett.py.\nextends RefCounted\n'
    for key,value in [('THEMES',themes),('WARP_MAPS',warps),('DUNGEONS',places),('MUSIC',music)]:
        text+='const '+key+' := '+json.dumps(value,ensure_ascii=False,indent=2)+'\n'
    (fm.ROOT/'scripts/data/route11_diglett.gd').write_text(text)

def connect_city():
    city=read('kanto_east');road=read('route11')
    area=next(a for a in city['areas'] if a['id']=='vermilion_city')
    native_city=fm.bake_layout(fm.layout_of(fm.map_json('VermilionCity')['layout']))
    native_road=fm.bake_layout(fm.layout_of(fm.map_json('Route11')['layout']))
    offset=-next(c['offset'] for c in fm.map_json('Route11')['connections'] if c['direction']=='left')
    lanes=[y for y in range(1,road['height']-1) if all(
        native_city['solid'][y+offset][native_city['w']-1-i]==0 and native_road['solid'][y][i]==0 for i in (0,1))]
    assert lanes,'No native Vermilion/Route 11 walking lane'
    for name,j,inward in [('kanto_east',city,[-1,0]),('route11',road,[1,0])]:
        rows=[list(row) for row in j['solid']]
        j['warps']=[w for w in j['warps'] if not w.get('route11_link')]
        cells=set()
        for y in lanes:
            x,yy=(area['x']+area['w']-1,area['y']+offset+y) if name=='kanto_east' else (0,y)
            rows[yy][x]='0';cells.add((x,yy))
            j['warps'].append(dict(x=x,y=yy,map='vermilion_city' if name=='kanto_east' else 'route11',index=5000+y,
                to='route11' if name=='kanto_east' else 'vermilion_city',to_warp=5000+y,
                arrival_dir=inward,edge_transition=True,route11_link=True))
        j['solid']=[''.join(row) for row in rows]
        if name=='route11':j['start']=[2*16+8,lanes[0]*16+8]
        write(name,j)
        metadata=read(name,'hd2d_cards.json');metadata['cards']=remove_cells(metadata['cards'],cells)
        write(name,metadata,'hd2d_cards.json')
        patch_path=OUT/name/'collision_patch.json'
        patch=json.loads(patch_path.read_text()) if patch_path.exists() else dict(open=[],block=[])
        patch['block']=[c for c in patch.get('block',[]) if tuple(c) not in cells]
        patch['open']=[c for c in patch.get('open',[]) if tuple(c) not in cells]+[list(c) for c in sorted(cells)]
        write(name,patch,'collision_patch.json')
    print('Vermilion east lanes',lanes)

def main():
    definitions()
    import hd2d_cards
    for folder in FOLDERS:
        name=fm.snake(folder)
        fm.bake([folder],name,None,False)
        j=read(name)
        spawn=next((w for w in j['warps'] if w['index']==1),j['warps'][0])
        if name=='route11':spawn=dict(x=2,y=10)
        j['start']=[spawn['x']*16+8,spawn['y']*16+8]
        # An indoor exit mat is a valid entrance spawn; overworld starts use
        # an adjacent clear tile so reopening a map never starts inside rock.
        if name in CAVES:
            for dx,dy in [(0,1),(0,-1),(-1,0),(1,0)]:
                x,y=spawn['x']+dx,spawn['y']+dy
                if j['solid'][y][x]=='0' and not any(w['x']==x and w['y']==y for w in j['warps']):
                    j['start']=[x*16+8,y*16+8];break
        write(name,j)
        if name=='route11':
            from kanto_water import rows as water_rows
            write(name,dict(water=water_rows(folder)),'water.json')
        hd2d_cards.build(name)
    connect_city()
    from fly_map_assets import main as fly_map
    fly_map()
    print('Route 11, east gate, Diglett cave and both Route 2-side buildings ready')

if __name__=='__main__':main()
