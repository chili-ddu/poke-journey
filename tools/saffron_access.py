"""Open the native Saffron north/south gates without Tea, badges or story flags."""
import json
import re
import frlg_map as fm

ROOT=fm.ROOT
OUT=ROOT/'assets/maps'
FOLDERS=['SaffronCity','SaffronCity_PokemonCenter_1F','SaffronCity_Mart']


def definitions():
    names={'saffron_city':'노랑시티','saffron_city_pokemon_center_1f':'노랑시티 포켓몬센터','saffron_city_mart':'노랑시티 프렌들리숍'}
    themes={};warps={};places={};music={}
    for folder in FOLDERS:
        name=fm.snake(folder)
        themes[name]=dict(map='res://assets/maps/'+name,tiles={})
        warps[name]=name
        cfg=dict(name=folder.upper(),name_ko=names[name],theme=name,count=0,encounters=[])
        cfg['overworld' if name=='saffron_city' else 'indoor']=True
        if name=='saffron_city':
            cfg['areas']={name:dict(name='SAFFRON CITY',name_ko=names[name])}
        elif name.endswith('pokemon_center_1f'):
            cfg['npcs']=[dict(id='nurse',sprite='nurse',tile=[7,2],face='down',talk='nurse',talk_tile=[7,4],heal_spot=[6.0,1.7])]
        else:
            cfg['npcs']=[dict(id='clerk',sprite='clerk',tile=[2,3],face='right',talk='shop',talk_tile=[4,3])]
        places[name]=cfg
        music[name]=fm.map_json(folder)['music'].lower()
    from cerulean_progression import dump
    text='# Generated by tools/saffron_access.py; city access has no story or item gate.\nextends RefCounted\n'
    for key,value in [('THEMES',themes),('WARP_MAPS',warps),('DUNGEONS',places),('MUSIC',music)]:
        encoded=re.sub(r'"heal_spot":\s*\[\s*([\d.]+),\s*([\d.]+)\s*\]',r'"heal_spot": Vector2(\1, \2)',dump(value))
        text+='const '+key+' := '+encoded+'\n'
    (ROOT/'scripts/data/saffron_access.gd').write_text(text)


def main():
    definitions()
    import hd2d_cards
    for folder in FOLDERS:
        name=fm.snake(folder)
        fm.bake([folder],name,(34,7) if name=='saffron_city' else None,False)
        path=OUT/name/'map.json'
        data=json.loads(path.read_text())
        if name.endswith('pokemon_center_1f'):
            data['warps']=[w for w in data['warps'] if not w['to'].endswith('_2f')]
        if name!='saffron_city':
            spawn=next(w for w in data['warps'] if w['index']==1)
            data['start']=[spawn['x']*16+8,(spawn['y']-1)*16+8]
        path.write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n')
        hd2d_cards.build(name)
    from fly_map_assets import main as fly_map
    fly_map()
    print('Saffron open: Route 5 gate <-> city <-> Route 6 gate; native center/shop; visited-only Fly destination.')


if __name__=='__main__':main()
